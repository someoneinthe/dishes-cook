// Generates eslint.sonar-rules.json: the rules SonarQube Cloud checks on the app's code (its quality
// profile for TypeScript, read from its public API) that the rest of the ESLint config leaves off,
// so `npm run lint` finds what would fail the quality gate on a PR. Each Sonar rule is matched to
// its ESLint rule by eslint-plugin-sonarjs (its rules' docs URLs and its README's table of the
// other plugins' rules). Rules of plugins this project doesn't use, rules without an ESLint
// equivalent, the rules eslint.config.mjs turns off on purpose ('off': Hermes lacks the APIs
// they push, a random pick is the app's purpose…), the formatting rules eslint-config-prettier
// turns off after them (Prettier owns formatting) and the exceptions below are left out.
//
//   npm run lint:sonar-rules             rewrites eslint.sonar-rules.json
//   npm run lint:sonar-rules -- --check  fails if SonarQube Cloud's rules changed since
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';

const ROOT = path.resolve(import.meta.dirname, '..');
const RULES_PATH = path.join(ROOT, 'eslint.sonar-rules.json');
const SONAR_API = 'https://sonarcloud.io/api';
// The name of the config block loading eslint.sonar-rules.json, left out to find the rules the rest
// of the config leaves off.
const GENERATED_BLOCK_NAME = 'sonar/generated';
// An app file the generated rules apply to (sonar-project.properties: src without the tests).
const APP_FILE = 'src/features/recipes/recipe-detail-screen.tsx';
const PAGE_SIZE = 500;

// Sonar rules left out, by key, and why.
const EXCEPTION_MAP = new Map([
  // Sonar's own version of these accepts code that the ESLint rule flags (no open issue on main).
  ['S1186', 'Sonar allows the empty functions the ESLint rule flags (no-op callbacks).'],
  // Ignored in SonarQube Cloud too (sonar-project.properties).
  ['S3317', 'Expo Router needs its file names (`_layout.tsx`, `index.tsx`).'],
  ['S3499', 'perfectionist sorts object keys alphabetically, shorthand or not.'],
  ['S3524', 'Prettier always writes `(x) => …`.'],
  ['S4023', 'Sonar allows the empty interfaces Unistyles needs to declare its themes.'],
  ['S6749', 'Sonar allows the fragments the ESLint rule flags (Markdown rendering).'],
  ['S6754', 'Sonar allows the `useState` names the ESLint rule flags.'],
]);

// ESLint options of Sonar rules with parameters, from the profile's values.
const OPTION_MAP = new Map([
  ['S107', (parameterMap) => [Number(parameterMap.get('maximumFunctionParameters'))]],
  ['S4622', (parameterMap) => [{ threshold: Number(parameterMap.get('threshold')) }]],
]);

const require = createRequire(path.join(ROOT, 'package.json'));

const projectProperties = await readProperties(path.join(ROOT, 'sonar-project.properties'));
const activeRuleList = await readActiveRules({
  organization: projectProperties.get('sonar.organization'),
  project: projectProperties.get('sonar.projectKey'),
});
const eslintRuleMap = await readEslintEquivalents();
const isRuleOn = await readBaseConfig();
const offRuleSet = await readOffRules(path.join(ROOT, 'eslint.config.mjs'));

const generatedRuleList = activeRuleList
  .filter(({ key }) => !EXCEPTION_MAP.has(key))
  .flatMap(({ key, name, parameterMap }) => {
    const eslintRuleList = (eslintRuleMap.get(key) ?? []).filter(
      (rule) => isRuleOn(rule) !== undefined,
    );
    const isLeftOut = eslintRuleList.some((rule) => isRuleOn(rule) || offRuleSet.has(rule));
    if (isLeftOut || eslintRuleList.length === 0) {
      return [];
    }
    const [rule] = eslintRuleList;
    const options = OPTION_MAP.get(key)?.(parameterMap) ?? [];
    return { key, name, rule, setting: options.length > 0 ? ['error', ...options] : 'error' };
  })
  .toSorted((first, second) => first.rule.localeCompare(second.rule));

const generated = {
  description:
    'SonarQube Cloud rules the rest of the ESLint config leaves off, generated by `npm run lint:sonar-rules` (scripts/sonar-rules.mjs): do not edit.',
  rules: Object.fromEntries(generatedRuleList.map(({ rule, setting }) => [rule, setting])),
  sonarRules: Object.fromEntries(
    generatedRuleList.map(({ key, name, rule }) => [rule, `${key}: ${name}`]),
  ),
};
const next = await format(JSON.stringify(generated), {
  ...(await resolveConfig(RULES_PATH)),
  filepath: RULES_PATH,
});
const current = await readCurrent();

if (process.argv.includes('--check')) {
  if (next === current) {
    console.warn('eslint.sonar-rules.json matches SonarQube Cloud.');
  } else {
    console.error(
      'SonarQube Cloud checks other rules: run `npm run lint:sonar-rules`, fix what `npm run lint` finds, and commit.',
    );
    process.exitCode = 1;
  }
} else if (next === current) {
  console.warn('eslint.sonar-rules.json is already up to date.');
} else {
  await writeFile(RULES_PATH, next);
  console.warn(`eslint.sonar-rules.json updated: ${generatedRuleList.length} rules.`);
}

// SonarQube Cloud's API, read without a token (the project is public).
async function fetchSonar(endpoint, parameterMap) {
  const url = `${SONAR_API}/${endpoint}?${new URLSearchParams(parameterMap)}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`SonarQube Cloud answered ${response.status} to ${url}`);
  }
  return response.json();
}

// The rules of the project's TypeScript quality profile, with their parameters' values.
async function readActiveRules({ organization, project }) {
  const { profiles } = await fetchSonar('qualityprofiles/search', { organization, project });
  const profile = profiles.find(({ language }) => language === 'ts');
  const ruleList = [];
  for (let page = 1; ; page += 1) {
    const { actives, rules, total } = await fetchSonar('rules/search', {
      activation: 'true',
      // The profile's activations, with the parameters' values.
      actives: 'true',
      f: 'name,actives',
      organization,
      p: String(page),
      ps: String(PAGE_SIZE),
      qprofile: profile.key,
    });
    for (const { key, name } of rules) {
      const parameterList = actives[key]?.find(({ qProfile }) => qProfile === profile.key)?.params;
      ruleList.push({
        key: key.split(':', 2)[1],
        name,
        parameterMap: new Map((parameterList ?? []).map(({ key: name, value }) => [name, value])),
      });
    }
    if (page * PAGE_SIZE >= total) {
      return ruleList;
    }
  }
}

// Whether a rule is on in the ESLint config without the generated block, for an app file: true, false,
// or undefined when the rule doesn't exist here (a plugin this project doesn't use).
async function readBaseConfig() {
  const { ESLint } = require('eslint');
  const { builtinRules } = require('eslint/use-at-your-own-risk');
  const { default: configList } = await import(
    pathToFileURL(path.join(ROOT, 'eslint.config.mjs')).href
  );
  const eslint = new ESLint({
    baseConfig: configList.filter(({ name }) => name !== GENERATED_BLOCK_NAME),
    cwd: ROOT,
    overrideConfigFile: true,
  });
  const config = await eslint.calculateConfigForFile(APP_FILE);
  return (rule) => {
    const pluginName = rule.includes('/') ? rule.slice(0, rule.lastIndexOf('/')) : undefined;
    const isKnown =
      pluginName === undefined
        ? builtinRules.has(rule)
        : Object.hasOwn(config.plugins[pluginName]?.rules ?? {}, rule.slice(pluginName.length + 1));
    if (!isKnown) {
      return;
    }
    const [severity] = [config.rules[rule] ?? 0].flat();
    return severity !== 0 && severity !== 'off';
  };
}

// The rules file as committed; none yet the first time.
async function readCurrent() {
  try {
    return await readFile(RULES_PATH, 'utf8');
  } catch {
    return '';
  }
}

// Sonar rule keys (S107…) and their ESLint rules: eslint-plugin-sonarjs's own, by their docs URL,
// and the other plugins' from its README's table.
async function readEslintEquivalents() {
  const { rules } = require('eslint-plugin-sonarjs');
  const ruleMap = new Map();
  const add = (key, rule) => ruleMap.set(key, [...(ruleMap.get(key) ?? []), rule]);
  for (const [name, { meta }] of Object.entries(rules)) {
    const key = /\/(S\d+)\b/.exec(meta?.docs?.url ?? '')?.[1];
    if (key) {
      add(key, `sonarjs/${name}`);
    }
  }
  const readme = await readFile(require.resolve('eslint-plugin-sonarjs/README.md'), 'utf8');
  for (const [, key, rule] of readme.matchAll(/^\|\s*(S\d+)\s*\|\s*\[([^\]]+)\]/gm)) {
    add(
      key,
      rule
        .replace(/^typescript-eslint\//, '@typescript-eslint/')
        .replace(/^@stylistic\/eslint-plugin\//, '@stylistic/')
        .replace(/^eslint\//, ''),
    );
  }
  return ruleMap;
}

// The rules eslint.config.mjs turns off itself ('rule': 'off'), not left off by a plugin's preset,
// and the formatting rules eslint-config-prettier turns off at its end, after the generated ones.
async function readOffRules(file) {
  const text = await readFile(file, 'utf8');
  const { rules: prettierRuleMap } = require('eslint-config-prettier');
  return new Set([
    ...[...text.matchAll(/'([^'\s]+)': 'off'/g)].map(([, rule]) => rule),
    ...Object.keys(prettierRuleMap).filter((rule) => [0, 'off'].includes(prettierRuleMap[rule])),
  ]);
}

async function readProperties(file) {
  const text = await readFile(file, 'utf8');
  return new Map(
    text
      .split('\n')
      .filter((line) => line.includes('=') && !line.startsWith('#'))
      .map((line) => [
        line.slice(0, line.indexOf('=')).trim(),
        line.slice(line.indexOf('=') + 1).trim(),
      ]),
  );
}
